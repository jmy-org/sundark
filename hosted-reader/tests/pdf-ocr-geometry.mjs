import assert from 'node:assert/strict';
import { buildSentenceSegments, normalizeSegments } from '../lib/source-geometry.ts';
const atom = (id,text,x,y,para='p1-a') => ({id,text,bbox:[x,y,.25,.025],para});
const wrapped = buildSentenceSegments([atom('a','A sentence wraps',.1,.1),atom('b','across two lines.',.1,.14)],1,'text');
assert.equal(wrapped.length,1); assert.equal(wrapped[0].rects.length,2);
assert.deepEqual(wrapped[0].sourceIds,['a','b']); assert.equal(wrapped[0].schemaVersion,2);
const columns = buildSentenceSegments([atom('l1','Left top.',.1,.1,'left'),atom('l2','Left bottom.',.1,.7,'left'),atom('r1','Right top.',.6,.1,'right')],1,'text');
assert.deepEqual(columns.map(s=>s.text),['Left top.','Left bottom.','Right top.']);
const two = buildSentenceSegments([atom('shared','First sentence. Second sentence.',.1,.1)],1,'text');
assert.equal(two.length,2); assert.deepEqual(two[0].rects,two[1].rects);
assert.equal(two[0].geometryPrecision,'pdf-item');
const ocr = buildSentenceSegments([atom('w1','First',.1,.1),atom('w2','sentence.',.4,.1),atom('w3','Next.',.1,.14)],1,'ocr');
assert.equal(ocr.length,2); assert.equal(ocr[0].para,ocr[1].para);
assert.equal(ocr[0].geometryPrecision,'ocr-word'); assert.equal(ocr[0].rects.length,2);
const fragment = buildSentenceSegments([atom('f1','inter',.1,.1),{...atom('f2','national.',.2,.1),joinBefore:''}],1,'text');
assert.equal(fragment[0].text,'international.');
const legacy = [{id:'legacy-stable',text:'Existing text',bbox:[.1,.1,.2,.1]}];
assert.deepEqual(normalizeSegments(legacy,1),legacy);
assert.deepEqual(normalizeSegments(JSON.parse(JSON.stringify(wrapped)),1),wrapped);
assert.throws(()=>normalizeSegments([{...wrapped[0],rects:[{page:2,bbox:[.1,.1,.1,.1]}]}],1));
assert.throws(()=>normalizeSegments([{...wrapped[0],bbox:[.9,.1,.2,.1]}],1));
assert.throws(()=>normalizeSegments([{...wrapped[0],para:'x'.repeat(81)}],1));
assert.throws(()=>normalizeSegments([{...wrapped[0],sourceIds:['x'.repeat(81)]}],1));
assert.throws(()=>normalizeSegments([{...wrapped[0],rects:Array(129).fill(wrapped[0].rects[0])}],1));
assert.throws(()=>normalizeSegments([{...wrapped[0],sourceIds:Array(129).fill('x')}],1));
assert.throws(()=>normalizeSegments([wrapped[0],wrapped[0]],1));
assert.throws(()=>normalizeSegments([{...legacy[0],text:'x'.repeat(80001)}],1));
const heavy = Array.from({length:30},(_,i)=>({...wrapped[0],id:`heavy-${i}`,sourceIds:Array.from({length:128},(_,j)=>`${j}-${'x'.repeat(70)}`)}));
assert.throws(()=>normalizeSegments(heavy,1),/300KB/);
console.log('PASS: sentence/paragraph provenance, independent multi-box geometry, no row sort, item precision, OCR word boxes, legacy IDs, metadata quotas.');
