// Builds the self-contained attachment reader widget: one HTML string with PDF.js, its
// worker (run on the main thread) and the reader inlined. The widget runs inside the
// host's sandbox, where the Site's /vendor paths are not reachable.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const zodEntry = createRequire(fileURLToPath(import.meta.resolve('@openai/mcp-extensions/app'))).resolve('zod');
const zod4 = zodEntry.slice(0, zodEntry.lastIndexOf('/node_modules/zod/') + '/node_modules/zod'.length);
const out = await build({
  entryPoints: [`${root}/client/attachment-reader/main.ts`], bundle: true, write: false, format: 'iife',
  platform: 'browser', target: 'es2022', minify: true, legalComments: 'none', charset: 'utf8',
  // pdf.js references Node modules behind runtime checks; the browser path never loads them.
  external: ['module', 'fs', 'path', 'url', 'http', 'https', 'zlib', 'canvas'],
  define: { 'process.env.NODE_ENV': '"production"' },
  // One zod 4 for the MCP Apps SDKs (the Site's own zod 3 stays untouched); their
  // peer ranges accept zod 4, and two copies would add ~280 KiB.
  alias: { zod: zod4, 'zod/v4': `${zod4}/v4` },
  logLevel: 'warning',
});
// Inline <script> text must not close the element or open an HTML comment.
const js = out.outputFiles[0].text.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');
const template = await readFile(`${root}/client/attachment-reader/template.html`, 'utf8');
if (!template.includes('/*BUNDLE*/')) throw new Error('Template is missing its bundle slot.');
const html = template.replace('/*BUNDLE*/', () => js);
await mkdir(`${root}/lib/generated`, { recursive: true });
await writeFile(`${root}/lib/generated/attachment-reader-html.ts`,
  `// Generated by scripts/build-attachment-reader.mjs. Do not edit.\nexport const html: string = ${JSON.stringify(html)};\n`);
console.log(`Built attachment reader widget (${Math.round(html.length / 1024)} KiB).`);
